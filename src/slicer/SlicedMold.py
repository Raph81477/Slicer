from pathlib import Path

import numpy as np
import pyvista as pv
from scipy.spatial import ConvexHull, Delaunay, cKDTree
from vtkmodules.util.numpy_support import vtk_to_numpy
from vtkmodules.vtkCommonCore import vtkIdList, vtkPoints
from vtkmodules.vtkCommonDataModel import vtkStaticCellLocator

from oamc.core import CompositeModel
from slicer.SlicedObject import SlicedObject


class _RayCaster:
    """
    Segment/mesh intersection tester that builds its spatial locator ONCE.

    `PolyData.ray_trace` may rebuild a locator on every call depending on
    the PyVista version, which is prohibitive when it is called once per
    node/face/ray. This helper keeps a single vtkStaticCellLocator.
    """

    def __init__(self, surface: pv.PolyData):
        self._surface = surface  # keep a reference: the locator does not own it
        self._locator = vtkStaticCellLocator()
        self._locator.SetDataSet(surface)
        self._locator.BuildLocator()
        self._tol = float(np.finfo(np.float32).eps)

    def hits(self, start, end) -> np.ndarray:
        """All intersection points of the segment [start, end] with the mesh, shape (n, 3)."""
        points = vtkPoints()
        points.SetDataTypeToDouble()
        cell_ids = vtkIdList()
        self._locator.IntersectWithLine(
            [float(c) for c in start], [float(c) for c in end], self._tol, points, cell_ids
        )
        if points.GetNumberOfPoints() == 0:
            return np.empty((0, 3))
        return vtk_to_numpy(points.GetData())


class SlicedMold(SlicedObject):
    """
    A sliced layer of the printed support/mold structure.

    Support layers are generated by building a "shadow volume" underneath
    the overhanging regions of the part and slicing it into printing
    layers. Unlike SlicedPiece, an approach/leave move's local normal is
    taken from the part's own outer surface (what the support is printed
    against), not from the support layer surface itself, so
    get_local_normals is overridden accordingly.

    Performance notes
    -----------------
    - The part's cell normals are computed once and shared by all the
      layers produced by slice_shadow_volume.
    - Ray casting uses a single locator (see _RayCaster) and only the
      rays that survive cheap vectorized filters are actually cast.
    - Slicing planes are cut in a single pass per direction.
    - Infill crossing detection is vectorized.
    """

    def __init__(
        self,
        surface: pv.PolyData,
        part_surface: pv.PolyData,
        q: int,
        z: float,
        contour_shells: list[np.ndarray] | None = None,
        infill_x: list[np.ndarray] | None = None,
        infill_y: list[np.ndarray] | None = None,
        infill_levels_x: np.ndarray | None = None,
        infill_levels_y: np.ndarray | None = None,
    ):
        super().__init__(surface)
        self.part_surface = part_surface  # goes through the setter below
        self.q = q
        self.z = z
        self.contour_shells = contour_shells or []
        self.infill_x = infill_x or []
        self.infill_y = infill_y or []
        # Fixed infill plane positions, computed once from layer zero and
        # shared by every layer so the infill paths stack vertically.
        self.infill_levels_x = infill_levels_x
        self.infill_levels_y = infill_levels_y

    # ------------------------------------------------------------------
    # Local normal override
    # ------------------------------------------------------------------

    @property
    def part_surface(self) -> pv.PolyData:
        return self._part_surface

    @part_surface.setter
    def part_surface(self, value: pv.PolyData) -> None:
        self._part_surface = value
        self._part_normals_cache = None

    @staticmethod
    def _unit_cell_normals(surface: pv.PolyData) -> np.ndarray:
        """Unit cell normals of a surface as a float64 array."""
        normals = np.array(surface.cell_normals, dtype=float)
        norms = np.linalg.norm(normals, axis=1, keepdims=True)
        norms[norms < 1e-12] = 1.0
        return normals / norms

    @property
    def _part_cell_normals(self) -> np.ndarray:
        """
        Cell normals of the part surface, computed once and cached
        (PyVista recomputes them on every access if the mesh does not
        store a normals array).
        """
        if self._part_normals_cache is None:
            self._part_normals_cache = self._unit_cell_normals(self.part_surface)
        return self._part_normals_cache

    def get_local_normals(self, points: np.ndarray) -> np.ndarray:
        """
        Support approach/leave moves are perpendicular to the part's own
        outer surface (what the support is printed against), not to the
        support layer surface itself.

        Batched version: one closest-cell query for all `points`
        (shape (n, 3)). The base class get_local_normal and the batched
        path helpers all go through this method.
        """
        points = np.atleast_2d(np.asarray(points, dtype=float))
        cell_ids = np.atleast_1d(self.part_surface.find_closest_cell(points))
        return self._part_cell_normals[cell_ids]

    # ------------------------------------------------------------------
    # Model-level utilities (pre-slicing)
    # ------------------------------------------------------------------

    @staticmethod
    def rotate_model(model: CompositeModel, rot_mat: np.ndarray) -> None:
        """Rotate the model's mesh nodes in place by the given rotation matrix."""
        model.mesh.nodes[:] = (rot_mat @ model.mesh.nodes.T).T
        model.mold.nodes[:] = (rot_mat @ model.mold.nodes.T).T
        object.__setattr__(model.mold, 'tree', cKDTree(model.mold.nodes))

        new_polydata = model.mold.polydata.copy()
        new_polydata.points = (rot_mat @ model.mold.polydata.points.T).T
        object.__setattr__(model.mold, 'polydata', new_polydata)

    @staticmethod
    def lift_model(model: CompositeModel, offset: float) -> None:
        """Translate the model's mesh nodes along Z by `offset`, in place."""
        model.mesh.nodes[:, 2] += offset
        model.mold.nodes[:, 2] += offset
        object.__setattr__(model.mold, 'tree', cKDTree(model.mold.nodes))

        new_polydata = model.mold.polydata.copy()
        new_polydata.points = model.mold.polydata.points.copy()
        new_polydata.points[:, 2] += offset
        object.__setattr__(model.mold, 'polydata', new_polydata)

    @staticmethod
    def solid_mesh_to_pyvista(solid_mesh) -> pv.UnstructuredGrid:
        """
        Convert a SolidMesh into a pv.UnstructuredGrid, automatically
        detecting each element's cell type from its node count.
        """
        nodes = solid_mesh.nodes
        connectivity = solid_mesh.connectivity
        n_elem, n_per_elem = connectivity.shape

        type_map = {
            4: pv.CellType.TETRA,
            8: pv.CellType.HEXAHEDRON,
            10: pv.CellType.QUADRATIC_TETRA,
            20: pv.CellType.QUADRATIC_HEXAHEDRON,
        }

        if n_per_elem not in type_map:
            raise ValueError(f"Unsupported element type: {n_per_elem} nodes")

        cell_type = type_map[n_per_elem]
        cells = np.hstack([
            np.full((n_elem, 1), n_per_elem, dtype=np.int64),
            connectivity.astype(np.int64)
        ]).ravel()
        cell_types = np.full(n_elem, cell_type, dtype=np.uint8)

        return pv.UnstructuredGrid(cells, cell_types, nodes)

    # ------------------------------------------------------------------
    # Shadow volume construction
    # ------------------------------------------------------------------

    @classmethod
    def _outer_surface(cls, model: CompositeModel, point_normals: bool = False) -> pv.PolyData:
        """
        Triangulated, linearized outer surface of the model's solid mesh,
        with cell normals (and optionally point normals). Shared by the
        three shadow-volume builders.
        """
        pv_mesh = cls.solid_mesh_to_pyvista(model.mesh)
        linear_mesh = pv_mesh.linear_copy()
        surface = linear_mesh.extract_surface(algorithm='dataset_surface')
        surface = surface.clean(tolerance=1e-6)
        surface = surface.triangulate()
        surface.compute_normals(cell_normals=True, point_normals=point_normals, inplace=True)
        return surface

    @staticmethod
    def _wedge_volume(
        top_pts: np.ndarray,
        bottom_pts: np.ndarray,
        triangles: np.ndarray,
    ) -> pv.UnstructuredGrid:
        """
        Build a volume of prisms (VTK wedges) between two point sheets.
        `triangles` index into top_pts; the same index + n_pts addresses
        the matching point of bottom_pts.
        """
        n_pts = len(top_pts)
        all_pts = np.vstack([top_pts, bottom_pts])  # bottom indexed from n_pts

        triangles = np.asarray(triangles, dtype=np.int64)
        n_tri = len(triangles)

        # Wedge = 6 nodes: top face (a, b, c), bottom face (a2, b2, c2)
        cells = np.hstack([
            np.full((n_tri, 1), 6, dtype=np.int64),
            triangles,
            triangles + n_pts,
        ]).ravel()
        cell_types = np.full(n_tri, pv.CellType.WEDGE, dtype=np.uint8)

        shadow = pv.UnstructuredGrid(cells, cell_types, all_pts)
        return shadow.clean(tolerance=1e-6)

    @classmethod
    def get_shadow_volume(cls, model: CompositeModel, plane_z: float = 0.0) -> pv.UnstructuredGrid:
        """
        Volume between the model's lower surface and the plane Z = plane_z.
        Each point of the lower surface is projected individually onto the
        plane (a variable "skirt" shape, not a uniform extrusion).
        """
        surface = cls._outer_surface(model, point_normals=False)

        # Downward-facing faces
        normals = surface.cell_data["Normals"]
        downward_mask = normals[:, 2] < 0
        n_down = downward_mask.sum()
        print(f"Downward-facing faces: {n_down} / {surface.n_cells}")

        if n_down == 0:
            raise ValueError(
                "No downward-facing face found - check that rotate_model() "
                "was applied before get_shadow_volume()"
            )

        bottom = surface.extract_cells(np.where(downward_mask)[0])
        bottom = bottom.extract_surface(algorithm='dataset_surface')
        bottom = bottom.triangulate()

        # Individually project each point of the lower surface onto the plane
        pts_top = bottom.points.copy()
        pts_bot = pts_top.copy()
        pts_bot[:, 2] = plane_z

        faces = bottom.faces.reshape(-1, 4)[:, 1:]  # triangles (n_tri, 3)
        shadow = cls._wedge_volume(pts_top, pts_bot, faces)

        print(f"Shadow volume: {shadow.volume:.3f} mm3")

        return shadow

    @classmethod
    def get_shadow_volume_cone(
        cls,
        model: CompositeModel,
        plane_z: float = 0.0,
        node_tol: float = 1.0,
        tri_tol: float = 1.0,
        offset_faces: float = 0.1,
        cone_angle: float = 30.0,
        no_rays: int = 8,
        start_phase: float = 0.0,
        distance_from_contour: float = 0.5,
    ) -> pv.UnstructuredGrid:
        """
        Compute the shadow volume using a cone of rays cast from the
        part's lower-surface faces.

        Parameters
        ----------
        node_tol             : max distance from a node to the outer surface
        tri_tol               : max distance from a centroid to the outer surface
        offset_faces          : offset of the centroid along the normal before
                                 casting rays (avoids self-intersection)
        cone_angle             : half-angle of the ray cone (degrees)
        no_rays               : number of rays in the cone (excluding the central ray)
        start_phase            : rotation of the cone around Z (degrees)
        distance_from_contour  : min distance from the projected centroid to the
                                  shadow contour to be included

        Performance: every test that does not need a ray cast (plane hit
        inside the bounds, distance to the shadow contour...) is evaluated
        for all faces at once; only the surviving (face, ray) pairs are
        actually cast, against a single locator.
        """
        # 1. Linearized outer surface
        surface = cls._outer_surface(model, point_normals=True)

        pts = surface.points
        normals = surface.cell_data["Normals"]
        faces = surface.faces.reshape(-1, 4)[:, 1:]  # (n_tri, 3)

        # 2. Pre-filter candidate triangles (outer surface, facing down)
        candidate_ids = np.where(normals[:, 2] < 0)[0]
        print(f"Candidate triangles (downward-facing normals): {len(candidate_ids)}")

        # 3. Shadow contour = convex hull of the XY projection of the surface
        pts_2d = pts[:, :2]

        print(f"Surface points: {len(pts_2d)}, X:[{pts_2d[:,0].min():.1f},{pts_2d[:,0].max():.1f}] Y:[{pts_2d[:,1].min():.1f},{pts_2d[:,1].max():.1f}]")

        hull = ConvexHull(pts_2d)
        hull_pts_2d = pts_2d[hull.vertices]
        boundary_tree = cKDTree(hull_pts_2d)

        print(f"Shadow contour (convex hull): {len(hull_pts_2d)} points")

        x_min, x_max = pts_2d[:, 0].min(), pts_2d[:, 0].max()
        y_min, y_max = pts_2d[:, 1].min(), pts_2d[:, 1].max()

        # 4. Ray cone: one central vertical ray + no_rays tilted rays
        cone_angle_rad = np.deg2rad(cone_angle)
        phis = np.deg2rad(start_phase) + 2 * np.pi * np.arange(no_rays) / no_rays
        cone_directions = np.vstack([
            [0.0, 0.0, -1.0],
            np.column_stack([
                np.sin(cone_angle_rad) * np.cos(phis),
                np.sin(cone_angle_rad) * np.sin(phis),
                np.full(no_rays, -np.cos(cone_angle_rad)),
            ]),
        ])

        ray_length = (pts[:, 2].max() - plane_z) * 2.0  # long enough to cross through

        # 5. Face-level vectorized setup
        centroids = pts[faces[candidate_ids]].mean(axis=1)           # (n, 3)
        origins = centroids + offset_faces * normals[candidate_ids]  # (n, 3)

        # Faces too close to the shadow contour are discarded
        dist_c, _ = boundary_tree.query(centroids[:, :2], workers=-1)
        keep = ~(dist_c < distance_from_contour)
        face_ids = candidate_ids[keep]
        origins = origins[keep]

        n_faces, n_dirs = len(face_ids), len(cone_directions)
        free = np.zeros((n_faces, n_dirs), dtype=bool)
        plane_hits = np.zeros((n_faces, n_dirs, 3))

        # 6. For each direction: cheap vectorized filters, then ray casts
        caster = _RayCaster(surface)

        for r, ray_dir in enumerate(cone_directions):
            if ray_dir[2] >= 0:
                continue  # ray pointing upward

            t = (plane_z - origins[:, 2]) / ray_dir[2]
            hit = origins + t[:, None] * ray_dir
            plane_hits[:, r] = hit

            candidates = np.flatnonzero(
                (hit[:, 0] >= x_min) & (hit[:, 0] <= x_max)
                & (hit[:, 1] >= y_min) & (hit[:, 1] <= y_max)
            )
            if len(candidates) == 0:
                continue

            dist_hit, _ = boundary_tree.query(hit[candidates, :2], workers=-1)
            candidates = candidates[dist_hit > distance_from_contour]

            for i in candidates:
                end = origins[i] + ray_length * ray_dir
                if len(caster.hits(origins[i], end)) == 0:  # ray not blocked
                    free[i, r] = True

        # Same output order as a face-by-face, ray-by-ray loop
        face_idx, ray_idx = np.nonzero(free)
        n_roof_faces = int(free.any(axis=1).sum())
        print(f"Roof faces: {n_roof_faces}, free ray pairs: {len(face_idx)}")

        # 7. Build the volume from the ray pairs
        if len(face_idx) == 0:
            raise ValueError("No free ray found - adjust the cone parameters")

        top_pts = origins[face_idx]                 # points on the part
        bottom_pts = plane_hits[face_idx, ray_idx]  # points on the plane (follow the ray, not vertical)

        # 2D Delaunay on the XY projections of top_pts to get a consistent surface
        triangles = Delaunay(top_pts[:, :2]).simplices
        shadow_volume = cls._wedge_volume(top_pts, bottom_pts, triangles)

        print(f"Z range: [{shadow_volume.points[:,2].min():.3f}, "
            f"{shadow_volume.points[:,2].max():.3f}] - plane_z={plane_z}")
        print(f"Volume: {shadow_volume.volume:.3f} mm3")

        return shadow_volume

    @classmethod
    def get_shadow_volume_vertical(
        cls,
        model: CompositeModel,
        plane_z: float = 0.0,
        offset_faces: float = 0.1,
    ) -> tuple[pv.UnstructuredGrid, pv.PolyData, pv.PolyData]:
        """
        Build the support volume by vertical projection from each node of
        the lower surface:
        - if the node -> plane segment does not cross the part: direct
          projection onto plane_z
        - if the segment crosses the part: take the first intersection as
          the lower point (volume between the node and the first
          intersection)

        Performance: a single ray-casting locator is built for the upward
        surface, and rays that cannot touch it (outside its bounding box)
        are skipped without being cast.
        """
        surface = cls._outer_surface(model, point_normals=True)

        pts = surface.points
        normals = surface.cell_data["Normals"]
        point_normals = surface.point_data["Normals"]
        faces = surface.faces.reshape(-1, 4)[:, 1:]

        # Nodes on the lower surface (normal with negative Z component)
        candidate_ids = np.where(normals[:, 2] < 0)[0]
        candidate_faces = faces[candidate_ids]
        # np.unique: sorted unique nodes + index of each face vertex in that list
        candidate_nodes, inverse = np.unique(candidate_faces.ravel(), return_inverse=True)
        face_node_idx = inverse.reshape(-1, 3)  # triangles indexing top_pts

        print(f"Candidate nodes: {len(candidate_nodes)}")

        # "Upward-facing" surface used for the intersection tests
        upward_ids = np.where(normals[:, 2] > 0)[0]
        upward_surface = surface.extract_cells(upward_ids)
        upward_surface = upward_surface.extract_surface(algorithm='dataset_surface')
        upward_surface = upward_surface.triangulate()

        print(f"Upward-facing faces: {len(upward_ids)} / {surface.n_cells}")

        caster = _RayCaster(upward_surface)
        ux_min, ux_max, uy_min, uy_max, uz_min, uz_max = upward_surface.bounds
        eps = 1e-6

        # ---- Per-node bottom points ---------------------------------------
        top_pts = pts[candidate_nodes]
        origins = top_pts + offset_faces * point_normals[candidate_nodes]

        # Default: direct projection onto the plane
        bottom_pts = top_pts.astype(float).copy()
        bottom_pts[:, 2] = plane_z

        # A vertical ray can only hit the upward surface inside its bounds
        may_hit = (
            (origins[:, 0] >= ux_min - eps) & (origins[:, 0] <= ux_max + eps)
            & (origins[:, 1] >= uy_min - eps) & (origins[:, 1] <= uy_max + eps)
            & (origins[:, 2] >= uz_min - eps) & (plane_z - 1.0 <= uz_max + eps)
        )

        for i in np.flatnonzero(may_hit):
            origin = origins[i]
            end = np.array([origin[0], origin[1], plane_z - 1.0])

            hits = caster.hits(origin, end)
            if len(hits) == 0:
                continue

            # The ray goes straight down: the first hit is the highest one
            first_hit = hits[np.argmax(hits[:, 2])]
            if first_hit[2] > plane_z:
                bottom_pts[i] = first_hit  # volume down to the intersection

        print(f"Top/bottom pairs: {len(top_pts)}")

        print(f"top_pts XY range: X[{top_pts[:,0].min():.2f}, {top_pts[:,0].max():.2f}] "
            f"Y[{top_pts[:,1].min():.2f}, {top_pts[:,1].max():.2f}]")

        # Just for visualizing the distribution of top_pts and bottom_pts
        cloud_top = pv.PolyData(np.array(top_pts))
        cloud_bot = pv.PolyData(bottom_pts)

        # ---- Maximum XY distance for a valid intersection --------------------
        tri_pts = pts[candidate_faces]  # (n_tri, 3, 3)
        edges = tri_pts - np.roll(tri_pts, -1, axis=1)
        max_xy_dist = np.linalg.norm(edges, axis=2).mean() * 2.0
        print(f"max_xy_dist: {max_xy_dist:.3f} mm")

        # ---- Prism validity test ----------------------------------------------
        a, b, c = face_node_idx[:, 0], face_node_idx[:, 1], face_node_idx[:, 2]
        centroid_top = (top_pts[a] + top_pts[b] + top_pts[c]) / 3.0
        origin_test = centroid_top + np.array([0, 0, -offset_faces])
        end_test = (bottom_pts[a] + bottom_pts[b] + bottom_pts[c]) / 3.0

        z_lo = np.minimum(origin_test[:, 2], end_test[:, 2])
        z_hi = np.maximum(origin_test[:, 2], end_test[:, 2])

        # Only segments whose bounding box overlaps the upward surface can
        # produce an intersection
        seg_min = np.minimum(origin_test, end_test)
        seg_max = np.maximum(origin_test, end_test)
        overlaps = (
            (seg_max[:, 0] >= ux_min - eps) & (seg_min[:, 0] <= ux_max + eps)
            & (seg_max[:, 1] >= uy_min - eps) & (seg_min[:, 1] <= uy_max + eps)
            & (seg_max[:, 2] >= uz_min - eps) & (seg_min[:, 2] <= uz_max + eps)
        )

        valid = np.ones(len(face_node_idx), dtype=bool)
        for k in np.flatnonzero(overlaps):
            hits = caster.hits(origin_test[k], end_test[k])
            if len(hits) == 0:
                continue

            # Keep only intersections truly between top and bottom and close in XY
            real = (
                (hits[:, 2] > z_lo[k]) & (hits[:, 2] < z_hi[k])
                & (np.linalg.norm(hits[:, :2] - origin_test[k, :2], axis=1) < max_xy_dist)
            )
            if real.any():
                valid[k] = False

        valid_triangles = face_node_idx[valid]
        if len(valid_triangles) == 0:
            raise ValueError("No valid prism - every triangle is blocked by the part")

        shadow = cls._wedge_volume(np.asarray(top_pts, dtype=float), bottom_pts, valid_triangles)

        print(f"Z range: [{shadow.points[:,2].min():.3f}, "
              f"{shadow.points[:,2].max():.3f}]")
        print(f"Volume: {shadow.volume:.3f} mm3")

        return shadow, cloud_top, cloud_bot

    @staticmethod
    def compute_shadow_contour(surface: pv.PolyData, plane_z: float, alpha: float = 5.0):
        """
        Compute the shadow contour (silhouette projected onto Z = plane_z)
        by working directly in 2D on the XY coordinates.
        """
        # Project every point onto Z = plane_z
        pts_2d = surface.points[:, :2].copy()  # keep XY only

        # Rebuild a flat 2D mesh to extract the boundary
        pts_3d_flat = np.column_stack([pts_2d, np.full(len(pts_2d), plane_z)])
        flat_surface = pv.PolyData(pts_3d_flat)

        # 2D Delaunay, forcing the projection axis
        shadow_2d = flat_surface.delaunay_2d(alpha=alpha, progress_bar=False)

        if shadow_2d.n_cells == 0:
            # Fallback: 2D convex hull via scipy
            hull = ConvexHull(pts_2d)
            hull_pts = pts_3d_flat[hull.vertices]
            # Close the polygon
            hull_pts = np.vstack([hull_pts, hull_pts[0]])
            boundary_pts_2d = hull_pts[:, :2]
            print("Warning: empty delaunay_2d -> falling back to 2D convex hull")
            return shadow_2d, boundary_pts_2d, cKDTree(boundary_pts_2d)

        # Extract the boundary
        boundary = shadow_2d.extract_feature_edges(
            boundary_edges=True,
            non_manifold_edges=False,
            feature_edges=False,
            manifold_edges=False,
        )

        if boundary.n_points == 0:
            raise ValueError("Empty shadow contour even after delaunay_2d - check alpha")

        boundary_pts_2d = boundary.points[:, :2]
        boundary_tree = cKDTree(boundary_pts_2d)

        print(f"Shadow contour: {len(boundary_pts_2d)} points")
        return shadow_2d, boundary_pts_2d, boundary_tree

    # ------------------------------------------------------------------
    # Legacy global slicing-plane infill (superseded by slice_shadow_volume,
    # kept for reference)
    # ------------------------------------------------------------------

    @staticmethod
    def generate_support_slicing_planes(
        shadow_volume: pv.UnstructuredGrid,
        infill_percentage: float = 20.0,
        plane_z: float = 0.0,
    ) -> tuple[list[dict], list[dict]]:
        """
        Generate two families of slicing planes (normal to X and normal to
        Y) for the fiber paths inside the support volume.

        The plane spacing is derived from the infill percentage:
        - 100% -> planes spaced one nozzle width apart (full infill)
        - 20%  -> planes spaced 5x the nozzle width apart

        Parameters
        ----------
        shadow_volume      : UnstructuredGrid of the support volume
        infill_percentage  : infill percentage (1-100)
        plane_z            : altitude of the printing plane

        Returns
        -------
        planes_x : list of {"origin", "normal"} dicts - planes normal to X
        planes_y : list of {"origin", "normal"} dicts - planes normal to Y
        """
        # 1. Extract the volume's surface to get the XY bounds
        surface = shadow_volume.extract_surface(algorithm='dataset_surface')
        bounds = surface.bounds
        # (xmin, xmax, ymin, ymax, zmin, zmax)
        x_min, x_max = bounds[0], bounds[1]
        y_min, y_max = bounds[2], bounds[3]
        z_min, z_max = bounds[4], bounds[5]

        print(f"Shadow volume bounds: "
              f"X[{x_min:.1f}, {x_max:.1f}] "
              f"Y[{y_min:.1f}, {y_max:.1f}] "
              f"Z[{z_min:.1f}, {z_max:.1f}]")

        # 2. Plane spacing from the infill percentage. For an XY grid:
        #    infill_pct = (nozzle_diameter / spacing)^2 * 100
        #    -> spacing = nozzle_diameter / sqrt(infill_pct / 100)
        nozzle_diameter = 0.70  # mm - matches the model's fiber_diameter

        spacing = SlicedMold.infill_spacing(nozzle_diameter, infill_percentage)

        print(f"Infill {infill_percentage}% -> plane spacing: {spacing:.3f} mm")

        orig = np.array([
            (x_min + x_max) / 2.0,
            (y_min + y_max) / 2.0,
            (z_min + z_max) / 2.0,
        ])

        # 3. Family 1: planes normal to X (YZ cuts)
        planes_x = [
            {"origin": np.array([x, orig[1], orig[2]]), "normal": np.array([1.0, 0.0, 0.0])}
            for x in np.arange(x_min, x_max + spacing, spacing)
        ]

        # 4. Family 2: planes normal to Y (XZ cuts)
        planes_y = [
            {"origin": np.array([orig[0], y, orig[2]]), "normal": np.array([0.0, 1.0, 0.0])}
            for y in np.arange(y_min, y_max + spacing, spacing)
        ]

        print(f"Planes generated: {len(planes_x)} normal to X, "
              f"{len(planes_y)} normal to Y")

        return planes_x, planes_y

    @staticmethod
    def infill_spacing(nozzle_diameter: float, infill_percentage: float) -> float:
        """Spacing of a two-direction grid (X + Y per layer, crossings counted once)
        giving the requested area/volume fraction."""
        ratio = np.clip(infill_percentage, 0.1, 100.0) / 100.0
        return nozzle_diameter / (1.0 - np.sqrt(1.0 - ratio))
    
    @staticmethod
    def generate_support_infill_lines(
        shadow_volume: pv.UnstructuredGrid,
        planes_x: list[dict],
        planes_y: list[dict],
    ) -> tuple[list[np.ndarray], list[np.ndarray]]:
        """
        Intersect the support volume with both plane families to generate
        the infill polylines.

        Returns
        -------
        infill_x : polylines from the planes normal to X
        infill_y : polylines from the planes normal to Y
        """
        surface = shadow_volume.extract_surface(algorithm='dataset_surface')
        surface = surface.triangulate()

        infill_x = []
        infill_y = []

        for plane in planes_x:
            cut = surface.slice(normal=plane["normal"], origin=plane["origin"])
            if cut.n_points > 0:
                infill_x.extend(SlicedObject.order_segments(cut))

        for plane in planes_y:
            cut = surface.slice(normal=plane["normal"], origin=plane["origin"])
            if cut.n_points > 0:
                infill_y.extend(SlicedObject.order_segments(cut))

        print(f"Polylines generated: {len(infill_x)} (X), {len(infill_y)} (Y)")

        return infill_x, infill_y

