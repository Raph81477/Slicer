    @staticmethod
    def segment_intersection_2d(
        p1: np.ndarray, p2: np.ndarray,
        q1: np.ndarray, q2: np.ndarray,
        tol: float = 1e-6,
    ) -> np.ndarray | None:
        """
        2D (XY) intersection between segments [p1, p2] and [q1, q2].
        Returns the 3D point interpolated on [p1, p2], or None if there is
        no intersection.

        Scalar reference version; the cutting code below uses the
        vectorized _segment_intersections_2d.
        """
        d1 = p2[:2] - p1[:2]
        d2 = q2[:2] - q1[:2]

        cross = d1[0] * d2[1] - d1[1] * d2[0]
        if abs(cross) < tol:
            return None  # parallel

        delta = q1[:2] - p1[:2]
        t = (delta[0] * d2[1] - delta[1] * d2[0]) / cross
        u = (delta[0] * d1[1] - delta[1] * d1[0]) / cross

        if 0 <= t <= 1 and 0 <= u <= 1:
            hit_2d = p1[:2] + t * d1
            hit_z = p1[2] + t * (p2[2] - p1[2])  # also interpolate Z
            return np.array([hit_2d[0], hit_2d[1], hit_z])

        return None

    @staticmethod
    def _segment_intersections_2d(
        p1: np.ndarray, p2: np.ndarray,
        q1: np.ndarray, q2: np.ndarray,
        tol: float = 1e-6,
    ) -> tuple[np.ndarray, np.ndarray]:
        """
        Vectorized XY intersection of N segment pairs ([p1, p2] x [q1, q2],
        each array of shape (N, 3)). Returns (hit_mask, t) where t is the
        parameter of the hit along [p1, p2].
        """
        d1 = p2[:, :2] - p1[:, :2]
        d2 = q2[:, :2] - q1[:, :2]

        cross = d1[:, 0] * d2[:, 1] - d1[:, 1] * d2[:, 0]
        delta = q1[:, :2] - p1[:, :2]

        with np.errstate(divide="ignore", invalid="ignore"):
            t = (delta[:, 0] * d2[:, 1] - delta[:, 1] * d2[:, 0]) / cross
            u = (delta[:, 0] * d1[:, 1] - delta[:, 1] * d1[:, 0]) / cross

        hit = (np.abs(cross) >= tol) & (t >= 0) & (t <= 1) & (u >= 0) & (u <= 1)
        return hit, t

    @staticmethod
    def interpolate_polyline_at(
        poly: np.ndarray,
        cum_lengths: np.ndarray,
        s: float,
    ) -> np.ndarray:
        """Interpolate a point on the polyline at curvilinear position s."""
        s = np.clip(s, 0, cum_lengths[-1])
        idx = np.searchsorted(cum_lengths, s, side='right') - 1
        idx = np.clip(idx, 0, len(poly) - 2)

        seg_len = cum_lengths[idx + 1] - cum_lengths[idx]
        if seg_len < 1e-12:
            return poly[idx]

        t = (s - cum_lengths[idx]) / seg_len
        return poly[idx] + t * (poly[idx + 1] - poly[idx])

    @classmethod
    def sample_polyline_between(
        cls,
        poly: np.ndarray,
        cum_lengths: np.ndarray,
        s_start: float,
        s_end: float,
    ) -> np.ndarray:
        """
        Extract the sub-segment of poly between curvilinear positions
        s_start and s_end, interpolating the exact cut points.
        """
        start_pt = cls.interpolate_polyline_at(poly, cum_lengths, s_start)
        end_pt = cls.interpolate_polyline_at(poly, cum_lengths, s_end)

        # Intermediate whole points (vectorized selection)
        inner = poly[(cum_lengths > s_start) & (cum_lengths < s_end)]

        return np.vstack([start_pt[None, :], inner, end_pt[None, :]])

    @classmethod
    def _cut_polyline_at_positions(
        cls,
        sec_poly: np.ndarray,
        cum_lengths: np.ndarray,
        cut_positions,
        cut_radius: float,
    ) -> list[np.ndarray]:
        """
        Remove a zone of +/- cut_radius (curvilinear) around every cut
        position from `sec_poly` and return the remaining sub-polylines.
        """
        total_length = cum_lengths[-1]
        cut_positions = np.unique(cut_positions)  # sorted, duplicates removed

        excluded = [
            (max(0, s - cut_radius), min(total_length, s + cut_radius))
            for s in cut_positions
        ]

        # Merge overlapping zones
        merged_excluded = []
        for start, end in excluded:
            if merged_excluded and start <= merged_excluded[-1][1]:
                merged_excluded[-1] = (merged_excluded[-1][0], max(merged_excluded[-1][1], end))
            else:
                merged_excluded.append((start, end))

        # Keep the non-excluded zones
        kept_intervals = []
        cursor = 0.0
        for excl_start, excl_end in merged_excluded:
            if cursor < excl_start:
                kept_intervals.append((cursor, excl_start))
            cursor = excl_end
        if cursor < total_length:
            kept_intervals.append((cursor, total_length))

        pieces = []
        for interval_start, interval_end in kept_intervals:
            if interval_end - interval_start < cut_radius:
                continue  # segment too short, ignore
            sub_pts = cls.sample_polyline_between(
                sec_poly, cum_lengths, interval_start, interval_end
            )
            if len(sub_pts) >= 2:
                pieces.append(sub_pts)
        return pieces

    @classmethod
    def _cut_secondary_lines(
        cls,
        infill_primary: list[np.ndarray],
        infill_secondary: list[np.ndarray],
        nozzle_diameter: float,
        neighbor_radius_extra: float | None,
    ) -> list[np.ndarray]:
        """
        Shared engine of the two cutting methods.

        neighbor_radius_extra=None  -> test every primary segment (exact, O(N*M))
        neighbor_radius_extra=value -> only test the primary segments whose
                                       midpoint is within
                                       seg_len/2 + value of the secondary
                                       segment's midpoint (KD-tree)
        """
        cut_radius = nozzle_diameter / 2.0

        # All primary segments as arrays
        q1_parts = [np.asarray(p, dtype=float)[:-1] for p in infill_primary if len(p) >= 2]
        q2_parts = [np.asarray(p, dtype=float)[1:] for p in infill_primary if len(p) >= 2]
        if not q1_parts:
            return infill_secondary
        Q1 = np.vstack(q1_parts)
        Q2 = np.vstack(q2_parts)
        n_prim = len(Q1)

        tree = None
        if neighbor_radius_extra is not None:
            tree = cKDTree(((Q1 + Q2) / 2.0)[:, :2])

        result = []

        for sec_poly in infill_secondary:
            if len(sec_poly) < 2:
                continue
            sec_poly = np.asarray(sec_poly)

            seg_lengths = np.linalg.norm(np.diff(sec_poly, axis=0), axis=1)
            cum_lengths = np.concatenate([[0], np.cumsum(seg_lengths)])
            if cum_lengths[-1] == 0:
                continue

            P1 = sec_poly[:-1].astype(float)
            P2 = sec_poly[1:].astype(float)
            n_seg = len(P1)

            # Candidate (secondary segment, primary segment) pairs
            if tree is None:
                pair_i = np.repeat(np.arange(n_seg), n_prim)
                pair_j = np.tile(np.arange(n_prim), n_seg)
            else:
                radius = seg_lengths / 2.0 + neighbor_radius_extra
                neighbors = tree.query_ball_point(((P1 + P2) / 2.0)[:, :2], r=radius)
                counts = np.fromiter((len(n) for n in neighbors), dtype=np.int64, count=n_seg)
                if counts.sum() == 0:
                    result.append(sec_poly)
                    continue
                pair_i = np.repeat(np.arange(n_seg), counts)
                pair_j = np.concatenate(
                    [np.asarray(n, dtype=np.int64) for n in neighbors if len(n)]
                )

            hit, t = cls._segment_intersections_2d(
                P1[pair_i], P2[pair_i], Q1[pair_j], Q2[pair_j]
            )
            if not hit.any():
                result.append(sec_poly)
                continue

            i_hit = pair_i[hit]
            seg_len_hit = seg_lengths[i_hit]
            # Curvilinear position of each intersection on sec_poly
            t_norm = np.clip(t[hit] * seg_len_hit / (seg_len_hit + 1e-12), 0, 1)
            cut_positions = cum_lengths[i_hit] + t_norm * seg_len_hit

            result.extend(
                cls._cut_polyline_at_positions(sec_poly, cum_lengths, cut_positions, cut_radius)
            )

        return result

    @classmethod
    def cut_infill_at_intersections(
        cls,
        infill_primary: list[np.ndarray],     # these lines stay continuous (not cut)
        infill_secondary: list[np.ndarray],   # these lines are cut at intersections
        nozzle_diameter: float = 0.70,
    ) -> list[np.ndarray]:
        """
        Cut the secondary lines at every intersection with the primary
        lines. Returns the cut secondary segments (crossing zones removed).

        The cut zone around each intersection is nozzle_diameter wide
        (half a nozzle width removed on each side).

        Exact version: tests every pair of segments (vectorized, but still
        O(N*M) - prefer cut_infill_at_intersections_fast on large layers).
        """
        return cls._cut_secondary_lines(
            infill_primary, infill_secondary, nozzle_diameter, neighbor_radius_extra=None
        )

    @classmethod
    def cut_infill_at_intersections_fast(
        cls,
        infill_primary: list[np.ndarray],
        infill_secondary: list[np.ndarray],
        nozzle_diameter: float = 0.70,
        infill_percentage: float = 20.0,
    ) -> list[np.ndarray]:
        """
        Fast version using a spatial index: instead of testing every pair,
        only test the primary segments close enough to each secondary
        segment (KD-tree on segment midpoints). The intersection tests
        themselves are vectorized per secondary polyline.
        """
        spacing = cls.infill_spacing(nozzle_diameter, infill_percentage)

        return cls._cut_secondary_lines(
            infill_primary,
            infill_secondary,
            nozzle_diameter,
            neighbor_radius_extra=spacing + nozzle_diameter,
        )

    # ------------------------------------------------------------------
    # Support printing path
    # ------------------------------------------------------------------

    @staticmethod
    def compute_max_connection_length(
        nozzle_diameter: float,
        infill_percentage: float,
        layer_height: float,
        margin: float = 1.1,
    ) -> float:
        """
        Geometrically compute max_connection_length as the diagonal between
        two adjacent lines (XY spacing, Z layer_height), with a safety
        margin.

        - 100% infill -> spacing = nozzle_diameter -> very short connections
        - 10%  infill -> large spacing -> longer connections accepted
        - layer_height bounds the vertical component
        """
        spacing = SlicedMold.infill_spacing(nozzle_diameter, infill_percentage)

        max_conn = np.sqrt(spacing**2 + layer_height**2) * margin
        print(f"Infill {infill_percentage}% -> spacing={spacing:.3f}, "
              f"max_connection_length={max_conn:.3f} mm")
        return max_conn

    @classmethod
    def collapse_infill_line(
        cls,
        points: np.ndarray,
        straight_tolerance: float = 0.05,
    ) -> np.ndarray:
        """
        Reduce an infill line to its two end points when it is a straight
        line (the normal case: infill lines are cuts of a planar layer by
        a plane x = const or y = const).

        Safety net: the line is only collapsed if it really is straight,
        i.e. every point lies within `straight_tolerance` of the chord
        between its end points AND the points progress monotonically
        along that chord (no back-and-forth). Otherwise the line is not
        a simple straight stroke (it may contain a jump or a turn): it is
        kept as a Ramer-Douglas-Peucker simplified polyline (or left
        untouched if it doubles back on itself) instead of being
        flattened - no jump is ever erased.
        """
        pts = np.asarray(points, dtype=float)
        if len(pts) <= 2:
            return pts

        a, b = pts[0], pts[-1]
        chord = b - a
        chord_len_sq = float(chord @ chord)
        if chord_len_sq < 1e-12:
            return cls.simplify_polyline(pts, straight_tolerance)

        t = (pts - a) @ chord / chord_len_sq
        dev = np.linalg.norm(pts - (a + t[:, None] * chord), axis=1)

        monotonic = np.all(np.diff(t) >= -1e-9)
        if not monotonic:
            # Back-and-forth along the line: RDP would flatten it (all the
            # points are on the chord), so keep the points untouched.
            return pts

        if dev.max() <= straight_tolerance:
            return np.array([a, b])

        return cls.simplify_polyline(pts, straight_tolerance)

    @classmethod
    def _make_crossing_blocker(cls, primary: list[np.ndarray]):
        """
        Return a callable (p_start, p_end) -> bool that is True when the
        straight move p_start -> p_end crosses (in XY) one of the primary
        lines. Such a move would be a printed connection laid across a
        primary bead, i.e. the crossing would be printed twice: it must
        be a leave/approach (travel) instead.
        """
        q1 = [np.asarray(p, dtype=float)[:-1] for p in primary if len(p) >= 2]
        q2 = [np.asarray(p, dtype=float)[1:] for p in primary if len(p) >= 2]
        if not q1:
            return None
        Q1, Q2 = np.vstack(q1), np.vstack(q2)
        n = len(Q1)

        def blocker(p_start, p_end) -> bool:
            a = np.broadcast_to(np.asarray(p_start, dtype=float), (n, 3))
            b = np.broadcast_to(np.asarray(p_end, dtype=float), (n, 3))
            hit, _ = cls._segment_intersections_2d(a, b, Q1, Q2)
            return bool(hit.any())

        return blocker

    def build_support_path(
        self,
        nozzle_diameter: float = 0.70,
        infill_percentage: float = 20.0,
        approach_distance: float = 1.0,
        layer_height: float = 0.35,
        shell_simplify_tolerance: float | None = None,
        collapse_infill: bool = False,
        infill_straight_tolerance: float = 0.05,
    ):
        """
        Build the full printing path for this support layer: contour
        shells first, then a zigzag infill where the primary direction (X
        or Y, alternating every other layer) stays continuous and the
        secondary direction is cut wherever it crosses the primary lines.

        Mold-specific simplification (applied to the curves BEFORE they
        are stitched, so every curve keeps its exact end points and the
        connections / approach / leave moves are unchanged):
        - shell_simplify_tolerance: contour shells stay sampled polylines
          but are simplified with Ramer-Douglas-Peucker (max deviation in
          mm). None = no simplification.
        - collapse_infill: infill lines are reduced to their two end
          points (see collapse_infill_line). Each cut piece of a
          secondary line stays a separate curve, so the gaps (jumps)
          between pieces are preserved.
        """
        max_connection_length = self.compute_max_connection_length(
            nozzle_diameter=nozzle_diameter,
            infill_percentage=infill_percentage,
            layer_height=layer_height,
        )

        def sort_zigzag(lines, axis):
            if not lines:
                return []
            sorted_lines = sorted(lines, key=lambda p: p[:, axis].mean())
            for i, poly in enumerate(sorted_lines):
                if i % 2 == 1:
                    sorted_lines[i] = poly[::-1]
            return sorted_lines

        # Prepare primary and secondary depending on parity
        infill_x_sorted = sort_zigzag(self.infill_x, axis=0)
        infill_y_sorted = sort_zigzag(self.infill_y, axis=1)

        if self.q % 2 == 0:
            primary, secondary_src, parity = infill_x_sorted, infill_y_sorted, "even -> X continuous, Y cut"
        else:
            primary, secondary_src, parity = infill_y_sorted, infill_x_sorted, "odd -> Y continuous, X cut"

        secondary = self.cut_infill_at_intersections_fast(
            infill_primary=primary,
            infill_secondary=secondary_src,
            nozzle_diameter=nozzle_diameter,
            infill_percentage=infill_percentage,
        )
        print(f"  Layer {self.q} ({parity})")

        active_infill = primary + secondary  # full list to print

        # Mold-specific simplification (after the cutting, which needs the
        # full-resolution primary lines)
        contour_shells = self.contour_shells
        if shell_simplify_tolerance is not None:
            contour_shells = [
                self.simplify_polyline(c, shell_simplify_tolerance)
                for c in contour_shells
            ]
        if collapse_infill:
            active_infill = [
                self.collapse_infill_line(c, infill_straight_tolerance)
                for c in active_infill
            ]
        min_len = 0.5 * nozzle_diameter

        def finalize(curves):
            if collapse_infill:
                curves = [self.collapse_infill_line(c, infill_straight_tolerance)
                          for c in curves]
            return [c for c in curves
                    if len(c) >= 2 and np.linalg.norm(c[-1] - c[0]) > min_len]

        primary_active = finalize(primary)
        active_infill = primary_active + finalize(secondary)

        # Pass 1: contour shells
        shell_segments, _, shell_types = self.build_path_single_pass(
            curves=contour_shells,
            approach_code=5,
            connection_end_code=3,
            continuation_code=2,
            approach_distance=approach_distance,
            max_connection_length=max_connection_length,
        )

        # Pass 2: infill (primary + cut secondary). A move that would cross
        # a primary line is forbidden as a connection (it would print the
        # crossing twice): it becomes a leave + approach (not printed).
        infill_segments, _, infill_types = self.build_path_single_pass(
            curves=active_infill,
            approach_code=4,
            connection_end_code=1,
            continuation_code=0,
            approach_distance=approach_distance,
            max_connection_length=max_connection_length,
            connection_blocker=self._make_crossing_blocker(primary_active),
        )

        all_segments = shell_segments + infill_segments
        all_types = shell_types + infill_types

        print(f"  primary: {len(primary)} lines")
        print(f"  secondary: {len(secondary)} lines")

        return all_segments, all_types

    # ------------------------------------------------------------------
    # Multi-layer path export (for external trajectory simulation, e.g. RoboDK)
    # ------------------------------------------------------------------

    @classmethod
    def export_layers_to_txt(
        cls,
        layers: list["SlicedMold"],
        filepath,
        nozzle_diameter: float = 0.70,
        infill_percentage: float = 20.0,
        approach_distance: float = 1.0,
        layer_height: float = 0.35,
        include_orientation: bool = False,
        approach_sign: float = -1.0,
        simplify_tolerance: float | None = None,
        shell_simplify_tolerance: float | None = None,
        collapse_infill: bool = False,
        infill_straight_tolerance: float = 0.05,
    ) -> None:
        """
        Build the full support printing path for every given layer and
        write the whole trajectory (all layers, in order) to a single
        text file, ready to be loaded by an external trajectory simulator
        such as RoboDK.

        Mold-specific simplification (recommended over simplify_tolerance):
        - shell_simplify_tolerance: RDP tolerance (mm) for the contour
          shells only (they stay polylines).
        - collapse_infill: infill lines are reduced to their two end
          points; jumps between lines / cut pieces are preserved.
        - infill_straight_tolerance: max deviation (mm) for an infill
          line to be considered straight (otherwise it is only RDP
          simplified, never flattened).

        simplify_tolerance: generic option, applied afterwards to every
        segment with Ramer-Douglas-Peucker (see
        SlicedObject.simplify_polyline). Leave it to None when using the
        mold-specific options above.
        """
        filepath = Path(filepath)

        for i, layer in enumerate(layers):
            segments, types = layer.build_support_path(
                nozzle_diameter=nozzle_diameter,
                infill_percentage=infill_percentage,
                approach_distance=approach_distance,
                layer_height=layer_height,
                shell_simplify_tolerance=shell_simplify_tolerance,
                collapse_infill=collapse_infill,
                infill_straight_tolerance=infill_straight_tolerance,
            )

            layer.export_printing_path(
                segments,
                types,
                filepath,
                include_orientation=include_orientation,
                approach_sign=approach_sign,
                simplify_tolerance=simplify_tolerance,
                layer_id=layer.q,
                mode="w" if i == 0 else "a",
            )

        print(f"Support path exported to {filepath} ({len(layers)} layers)")
